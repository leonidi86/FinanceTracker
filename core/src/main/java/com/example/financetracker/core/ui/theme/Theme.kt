/** Цвета приложения, которых нет в [androidx.compose.material3.ColorScheme]. */
@Immutable
data class ExtendedColors(val income: Color)

private val LightExtendedColors = ExtendedColors(income = IncomeLight)
private val DarkExtendedColors = ExtendedColors(income = IncomeDark)

private val LocalExtendedColors = staticCompositionLocalOf { LightExtendedColors }

/**
 * Динамические цвета Android 12+ не используются: приложение должно совпадать с макетами.
 */
@Composable
fun FinanceTrackerTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    content: @Composable () -> Unit
) {
    CompositionLocalProvider(
        LocalExtendedColors provides if (darkTheme) DarkExtendedColors else LightExtendedColors
    ) {
        MaterialTheme(
            colorScheme = if (darkTheme) DarkColorScheme else LightColorScheme,
            typography = Typography(),
            content = content
        )
    }
}

object FinanceTrackerTheme {
    val extendedColors: ExtendedColors
        @Composable
        get() = LocalExtendedColors.current
}
